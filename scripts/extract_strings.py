#!/usr/bin/env python3
"""Collects L("key", "English") / LF(...) calls into Resources/Localization/en.lproj/Localizable.strings."""
import re, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
pattern = re.compile(r'\bLF?\(\s*"([^"]+)"\s*,\s*"((?:[^"\\]|\\.)*)"')
strings = {}
for path in sorted((root / "Sources").rglob("*.swift")):
    for key, value in pattern.findall(path.read_text(encoding="utf-8")):
        if key in strings and strings[key] != value:
            sys.exit(f"Conflicting English text for {key}: {strings[key]!r} vs {value!r}")
        strings[key] = value
out = root / "Resources/Localization/en.lproj/Localizable.strings"
out.parent.mkdir(parents=True, exist_ok=True)
lines = ["/* Z-MarkDowner – English (development language). Generated by scripts/extract_strings.py */", ""]
for key in sorted(strings):
    lines.append(f'"{key}" = "{strings[key]}";')
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(strings)} strings -> {out.relative_to(root)}")
